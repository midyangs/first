def seed_if_empty() -> bool:
    """若 ranks 表为空，则导入示例数据。返回是否执行了导入。"""
    init_db()
    with get_conn() as conn:
        n = conn.execute("SELECT COUNT(*) AS c FROM ranks").fetchone()["c"]
        if n > 0:
            return False
        for r in SEED:
            conn.execute(
                """
                INSERT INTO ranks(id,title,cat,city,cover,grad,"desc",views,hot,self,status)
                VALUES (?,?,?,?,?,?,?,?,?,0,'published')
                """,
                (r["id"], r["title"], r["cat"], r["city"], r["cover"],
                 r["grad"], r["desc"], r["views"], r["hot"]),
            )
            for i, (n_, s, p, rr, a, e, tags) in enumerate(r["entries"], start=1):
                conn.execute(
                    """
                    INSERT INTO entries(rank_id,seq,n,s,p,r,a,e,tags,likes)
                    VALUES (?,?,?,?,?,?,?,?,?,0)
                    """,
                    (r["id"], i, n_, s, p, rr, a, e, _json(tags)),
                )
    return True


def _json(v):
    import json
    return json.dumps(v, ensure_ascii=False)


def bootstrap():
    """一键初始化：建表 + 示例数据 + 默认管理员。"""
    init_db()
    seeded = seed_if_empty()
    created_admin = ensure_default_admin()
    return {"seeded": seeded, "admin_created": created_admin}


if __name__ == "__main__":
    print(bootstrap())
